#!/usr/bin/env python3
"""Copy the approved map.html SVG, attaching the existing seat IDs by position.
No geometry is redrawn. Run after editing the original plan or venue data.
"""
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = '{http://www.w3.org/2000/svg}'
ET.register_namespace('', NS[1:-1])
source = (ROOT.parent / 'prototype/map.html').read_text()
original = re.search(r'<svg[^>]*\bid="seatmap".*?</svg>', source, re.S).group()
svg = ET.fromstring(original)
venue = json.loads((ROOT / 'venue-data-arena.js').read_text().removeprefix('window.VENUE = ').strip().removesuffix(';'))
circles = list(svg.iter(NS + 'circle'))
xs = [float(c.get('cx')) for c in circles]
ys = [float(c.get('cy')) for c in circles]
positions = [s['geometry']['coordinates'] for s in venue['seats']['features']]
cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
scale = (max(p[0] for p in positions) - min(p[0] for p in positions)) / (max(xs) - min(xs))
by_sector = {}
for f in venue['seats']['features']:
    by_sector.setdefault(f['properties']['s'], []).append(f)
matched = set()
worst_error = 0
for group in svg.iter(NS + 'g'):
    token = group.get('data-sector')
    if not token:
        continue
    token = token.replace('_x002f_', '/')
    is_table = '/' in token
    group.set('data-key', ('t:' if is_table else 's:') + token)
    group.set('data-kind', 'table' if is_table else 'section')
    pool = by_sector.get(token, [])
    for circle in group.iter(NS + 'circle'):
        x, y = float(circle.get('cx')), float(circle.get('cy'))
        def distance(feature):
            p = feature['geometry']['coordinates']
            return ((p[0] / scale + cx - x) ** 2 + (-p[1] / scale + cy - y) ** 2) ** .5
        candidate = min(pool, key=distance)
        error = distance(candidate)
        key = candidate['properties']['mk']
        assert error < .12 and key not in matched, (token, key, error)
        matched.add(key)
        worst_error = max(worst_error, error)
        circle.set('data-key', key)
        circle.set('data-kind', 'seat')
assert len(matched) == len(venue['seats']['features']) == len(circles)
svg.set('id', 'arena-plan-svg')
svg.attrib.pop('style', None)
# SVG <style> rules otherwise leak into every icon on the checkout page.
for style in svg.iter(NS + 'style'):
    style.text = re.sub(r'([^{}]+)\{', lambda m: ','.join('#arena-plan-svg ' + s.strip() for s in m[1].split(',')) + '{', style.text)
assert not list(svg.iter(NS + 'script')) and not list(svg.iter(NS + 'foreignObject'))
markup = ET.tostring(svg, encoding='unicode')
metadata = {'source': 'prototype/map.html#seatmap', 'sha256': hashlib.sha256(original.encode()).hexdigest(), 'seats': len(matched)}
(ROOT / 'arena-plan-svg.js').write_text('// Generated by tools/export-svg-plan.py from the approved site plan.\nwindow.ArenaPlanSVG = ' + json.dumps(markup, ensure_ascii=False) + ';\nwindow.ArenaPlanSource = ' + json.dumps(metadata) + ';\n')
print(f'Original SVG preserved; {len(matched)} seats matched uniquely; maximum rounding error {worst_error:.4f} SVG units.')
